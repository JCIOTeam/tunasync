            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
    esac
}

if [[ "${BASH_VERSINFO[0]}" -eq 4 && "${BASH_VERSINFO[1]}" -ge 4 || "${BASH_VERSINFO[0]}" -gt 4 ]]; then
    complete -F _tunasynctl -o nosort -o bashdefault -o default tunasynctl
else
    complete -F _tunasynctl -o bashdefault -o default tunasynctl
fi

# ── Dynamic completion for mirror names and worker IDs ───────────────────────
#
# Overrides the static completion functions generated above for subcommands
# that accept mirror names or worker IDs as positional arguments.
# Falls back silently if tunasynctl or jq is unavailable.
#
# Installation:
#   sudo cp tunasynctl.bash /etc/bash_completion.d/tunasynctl   # system-wide
#   tunasynctl completion bash >> ~/.bashrc && source ~/.bashrc  # per-user

_tunasynctl_mirrors() {
    local cache="/tmp/.tunasynctl_mirror_cache"
    if [[ -f "$cache" ]] && (( $(date +%s) - $(stat -c %Y "$cache" 2>/dev/null || echo 0) < 10 )); then
        cat "$cache"; return
    fi
    command -v jq &>/dev/null && \
        tunasynctl list --format json 2>/dev/null | jq -r '.[].name' 2>/dev/null | tee "$cache"
}

_tunasynctl_workers() {
    local cache="/tmp/.tunasynctl_worker_cache"
    if [[ -f "$cache" ]] && (( $(date +%s) - $(stat -c %Y "$cache" 2>/dev/null || echo 0) < 10 )); then
        cat "$cache"; return
    fi
    command -v jq &>/dev/null && \
        tunasynctl workers 2>/dev/null | jq -r '.[].id' 2>/dev/null | tee "$cache"
}

_tunasynctl_wrapped() {
    local i cur prev
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    # Call the clap-generated function first.
    _tunasynctl "$@"

    # Determine active subcommand.
    local subcmd=""
    for i in "${COMP_WORDS[@]:1:COMP_CWORD}"; do
        case "$i" in
            start|stop|disable|restart|set-size) subcmd="$i"; break ;;
            reload|rm-worker)                    subcmd="$i"; break ;;
        esac
    done

    # Inject dynamic completions for first positional arg (not a flag).
    [[ "$prev" == -* ]] && return
    case "$subcmd" in
        start|stop|disable|restart|set-size)
            mapfile -t COMPREPLY < <(compgen -W "$(_tunasynctl_mirrors)" -- "$cur") ;;
        reload|rm-worker)
            mapfile -t COMPREPLY < <(compgen -W "$(_tunasynctl_workers)" -- "$cur") ;;
    esac
}

complete -F _tunasynctl_wrapped -o nosort tunasynctl
